function prefixed(prefix: string, tokens: Record<string, string>) {
  return Object.fromEntries(
    Object.entries(tokens).map(([name, value]) => [`${prefix}${name}`, value]),
  );
}

function cssBlock(selector: string, tokens: Record<string, string>) {
  const lines = Object.keys(tokens)
    .sort()
    .map((name) => `  ${name}: ${tokens[name]};`);
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

function cssAsset(value: string | undefined) {
  if (!value) return "none";
  const escaped = value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\a ");
  return `url("${escaped}")`;
}

function brandBlock(
  selector: string,
  brand: BrandDefinition,
  theme: ThemeName,
) {
  const base = brand.base[theme];
  const mix = theme === "dark" ? "black" : "white";
  const tokens: Record<string, string> = {
    "--nerux-brand-name": JSON.stringify(brand.name),
    "--nerux-brand-base": base,
    "--nerux-brand-hover": `color-mix(in oklch, var(--nerux-brand-base) 88%, ${mix})`,
    "--nerux-brand-active": `color-mix(in oklch, var(--nerux-brand-base) 78%, ${mix})`,
    "--nerux-brand-disabled":
      "color-mix(in oklch, var(--nerux-brand-base) 45%, var(--nerux-color-bg))",
    "--nerux-brand-focus-ring":
      "color-mix(in oklch, var(--nerux-brand-base) 55%, transparent)",
    "--nerux-brand-foreground": bestForeground(base),
    "--nerux-brand-logo-light": cssAsset(brand.logoLight),
    "--nerux-brand-logo-dark": cssAsset(brand.logoDark),
    "--nerux-brand-favicon": cssAsset(brand.favicon),
  };
  return cssBlock(selector, tokens);
}

function buildPrimitivesCss() {
  const tokens = {
    ...prefixed("--nerux-primitive-", primitiveColors),
    ...prefixed("--nerux-", spacing),
    ...prefixed("--nerux-", radii),
    ...prefixed("--nerux-", typography),
    ...prefixed("--nerux-", transitions),
    ...prefixed("--nerux-", borders),
    "--nerux-border-default":
      "var(--nerux-border-width-normal) var(--nerux-border-style-solid) var(--nerux-color-border-default)",
    "--nerux-border-input":
      "var(--nerux-border-width-thin) var(--nerux-border-style-solid) var(--nerux-color-border-default)",
  };
  return header + cssBlock(":root", tokens);
}

function buildSemanticCss() {
  const lightTokens = {
    ...prefixed("--nerux-", semantic.light),
    ...prefixed("--nerux-", shadows.light),
  };
  const darkTokens = {
    ...prefixed("--nerux-", semantic.dark),
    ...prefixed("--nerux-", shadows.dark),
  };
  return (
    header +
    cssBlock(":root", prefixed("--nerux-", semantic.shared)) +
    "\n" +
    cssBlock(":root,\n:root[data-theme=\"light\"]", lightTokens) +
    "\n" +
    cssBlock(':root[data-theme="dark"]', darkTokens)
  );
}

function buildBrandsCss() {
  const names = Object.keys(brands).sort();
  const defaultBrandName = defaultBrand;
  const defaultDefinition = brands[defaultBrandName];
  const blocks: string[] = [];
  const derivedBrandTokens = (mix: string) => ({
    "--nerux-brand-hover": `color-mix(in oklch, var(--nerux-brand-base) 88%, ${mix})`,
    "--nerux-brand-active": `color-mix(in oklch, var(--nerux-brand-base) 78%, ${mix})`,
    "--nerux-brand-disabled":
      "color-mix(in oklch, var(--nerux-brand-base) 45%, var(--nerux-color-bg))",
    "--nerux-brand-focus-ring":
      "color-mix(in oklch, var(--nerux-brand-base) 55%, transparent)",
  });

  blocks.push(cssBlock("[data-brand]", derivedBrandTokens("white")));
  blocks.push(
    cssBlock('[data-brand][data-theme="dark"]', derivedBrandTokens("black")),
  );

  blocks.push(
    brandBlock(
      `:root,\n:root[data-brand="${defaultBrandName}"]`,
      defaultDefinition,
      "light",
    ),
  );
  blocks.push(
    brandBlock(
      `:root[data-theme="dark"],\n:root[data-brand="${defaultBrandName}"][data-theme="dark"]`,
      defaultDefinition,
      "dark",
    ),
  );

  for (const name of names) {
    if (name === defaultBrandName) continue;
    const definition = brands[name];
    blocks.push(
      brandBlock(`:root[data-brand="${name}"]`, definition, "light"),
    );
    blocks.push(
      brandBlock(
        `:root[data-brand="${name}"][data-theme="dark"]`,
        definition,
        "dark",
      ),
    );
  }

  const supportRules: string[] = [];
  for (const name of names) {
    const foreground = {
      "--nerux-brand-foreground":
        "contrast-color(var(--nerux-brand-base))",
    };
    supportRules.push(
      cssBlock(`:root[data-brand="${name}"]`, foreground),
    );
    supportRules.push(
      cssBlock(
        `:root[data-brand="${name}"][data-theme="dark"]`,
        foreground,
      ),
    );
  }
  const support = supportRules
    .map((rule) =>
      rule
        .split("\n")
        .filter((line) => line.length > 0)
        .map((line) => `  ${line}`)
        .join("\n"),
    )
    .join("\n");

  return (
    header +
    blocks.join("\n") +
    "\n@supports (color: contrast-color(red)) {\n" +
    support +
    "\n}\n"
  );
}

